'use strict';
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { spawnSync } = require('node:child_process');
const engine = process.argv[2];
if (!engine) { console.error('Usage: npm run check:runtime -- <Cocos engine directory containing bin/.declarations/cc.d.ts>'); process.exit(1); }
const declarations = path.resolve(engine, 'bin/.declarations/cc.d.ts');
if (!fs.existsSync(declarations)) throw new Error(`Engine declarations not found: ${declarations}`);
const root = path.resolve(__dirname, '..');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'cocos-inspector-types-'));
try {
    // These are build-time boolean flags generated by Creator, separate from engine API declarations.
    const env = path.join(temporary, 'cc-env.d.ts');
    fs.writeFileSync(env, "declare module 'cc/env' { export const EDITOR: boolean; export const DEBUG: boolean; }\n");
    const config = path.join(temporary, 'tsconfig.json');
    fs.writeFileSync(config, JSON.stringify({ compilerOptions: {
        target: 'ES2021', module: 'ESNext', moduleResolution: 'node', lib: ['ES2021', 'DOM'],
        strict: true, types: [], skipLibCheck: true, noEmit: true, experimentalDecorators: true,
    }, files: [declarations, env, ...fs.readdirSync(path.join(root, 'runtime')).filter(file => file.endsWith('.ts')).map(file => path.join(root, 'runtime', file))] }, null, 2));
    const result = spawnSync(process.execPath, [require.resolve('typescript/bin/tsc'), '-p', config, '--pretty', 'false'], { stdio: 'inherit' });
    if (result.error) throw result.error;
    process.exitCode = result.status || 0;
    if (result.status === 0) console.log('Runtime API typecheck passed against supplied engine declarations.');
} finally { fs.rmSync(temporary, { recursive: true, force: true }); }
